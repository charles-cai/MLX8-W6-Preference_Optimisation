@torch.no_grad()
def generate_task_pool(
    curriculum_model,
    curriculum_tokenizer,
    num_tasks: int = 200,
    max_new_tokens: int = 2048,
    temperature: float = 1.0,
    system_prompt: Optional[str] = None,
) -> List[str]:
    """Generate a pool of tasks from the frozen curriculum agent."""
    if system_prompt is None:
        system_prompt = """You are an expert competition-math problem setter. Generate a challenging problem with:
<question> The full problem statement </question>
\\boxed{final answer}"""
    
    user_prompt = "Generate one new, challenging reasoning question now."
    
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt},
    ]
    
    prompt_text = curriculum_tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True,
    )
    
    tasks = []
    logger.info(f"📝 Generating {num_tasks} tasks from curriculum agent...")
    
    for i in tqdm(range(num_tasks), desc="Generating tasks", unit="task"):
        inputs = curriculum_tokenizer(prompt_text, return_tensors="pt").to(curriculum_model.device)
        
        outputs = curriculum_model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            temperature=temperature,
            do_sample=True,
            top_p=0.99,
            pad_token_id=curriculum_tokenizer.pad_token_id,
        )
        
        task = curriculum_tokenizer.decode(
            outputs[0][inputs['input_ids'].shape[1]:],
            skip_special_tokens=True,
        )
        tasks.append(task)
    
    logger.success(f"✅ Generated {len(tasks)} tasks")
    return tasks


@torch.no_grad()
def sample_executor_responses(
    executor_model,
    executor_tokenizer,
    question: str,
    k: int = 4,
    max_new_tokens: int = 2048,
    temperature: float = 1.0,
) -> List[str]:
    """Sample k responses from executor for a given question."""
    messages = [
        {"role": "system", "content": "Solve the following problem step by step. Put your final answer in \\boxed{}."},
        {"role": "user", "content": question},
    ]
    
    prompt_text = executor_tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True,
    )
    inputs = executor_tokenizer(prompt_text, return_tensors="pt").to(executor_model.device)
    
    responses = []
    for _ in range(k):
        outputs = executor_model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            temperature=temperature,
            do_sample=True,
            top_p=0.99,
            pad_token_id=executor_tokenizer.pad_token_id,
        )
        
        response = executor_tokenizer.decode(
            outputs[0][inputs['input_ids'].shape[1]:],
            skip_special_tokens=True,
        )
        responses.append(response)
    
    return responses


