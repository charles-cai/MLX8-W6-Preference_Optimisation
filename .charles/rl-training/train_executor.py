def load_model_and_tokenizer(
    model_name: str,
    use_lora: bool = False,
    lora_r: int = 32,
    device_map: str = "auto",
    torch_dtype: Optional[torch.dtype] = None,
) -> tuple:
    """Load model and tokenizer with optional LoRA."""
    logger.info(f"📦 Loading model: {model_name}")
    
    if torch_dtype is None:
        if torch.cuda.is_available() and torch.cuda.is_bf16_supported():
            torch_dtype = torch.bfloat16
        else:
            torch_dtype = torch.float16
    
    tokenizer = AutoTokenizer.from_pretrained(
        model_name,
        trust_remote_code=True,
    )
    
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    
    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        torch_dtype=torch_dtype,
        device_map=device_map,
        trust_remote_code=True,
    )
    
    if use_lora:
        if not PEFT_AVAILABLE:
            raise ImportError("peft not installed. Run: pip install peft")
        
        logger.info(f"🔧 Applying LoRA with r={lora_r}")
        lora_config = LoraConfig(
            task_type=TaskType.CAUSAL_LM,
            r=lora_r,
            lora_alpha=lora_r * 2,
            lora_dropout=0.05,
            target_modules=["q_proj", "k_proj", "v_proj", "o_proj"],
        )
        model = get_peft_model(model, lora_config)
        model.print_trainable_parameters()
    
    num_params = sum(p.numel() for p in model.parameters())
    trainable_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    logger.success(f"✅ Model loaded: {num_params:,} total params, {trainable_params:,} trainable")
    
    return model, tokenizer


